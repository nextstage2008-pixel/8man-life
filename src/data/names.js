const DECADES = Object.keys(NAMES.male).map(Number).sort((a, b) => a - b);

// その年に生まれた人の名前の一覧。一覧のない年代は、それより前でいちばん近い年代（範囲の外は端）。
export function namesFor(sex, year) {
  const dec = Math.floor(year / 10) * 10;
  let pick = DECADES[0];
  for (const d of DECADES) if (d <= dec) pick = d;
  return NAMES[sex][pick];
}

